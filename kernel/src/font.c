bool font_knows(char c)
{
    return font_glyph(c) != glyph_unknown;
}

const uint8_t *font_glyph(char c)
{
    if (c == ' ') {
        return glyph_space;
    }
    if (c >= 'A' && c <= 'Z') {
        return glyphs_az[c - 'A'];
    }
    if (c >= 'a' && c <= 'z') {
        return glyphs_az_lower[c - 'a'];
    }
    if (c >= '0' && c <= '9') {
        return glyphs_09[c - '0'];
    }
    if (c == '+') {
        return glyph_plus;
    }
    if (c == '-') {
        return glyph_minus;
    }
    if (c == '=') {
        return glyph_equals;
    }
    if (c == '*') {
        return glyph_star;
    }
    if (c == '/') {
        return glyph_slash;
    }
    if (c == '^') {
        return glyph_caret;
    }
    if (c == '<') {
        return glyph_less;
    }
    if (c == '>') {
        return glyph_greater;
    }
    if (c == '.') {
        return glyph_dot;
    }
    if (c == ',') {
        return glyph_comma;
    }
    if (c == ':') {
        return glyph_colon;
    }
    if (c == '_') {
        return glyph_underscore;
    }
    if (c == '(') {
        return glyph_bracket_open;
    }
    if (c == ')') {
        return glyph_bracket_close;
    }
    if (c == '%') {
        return glyph_percent;
    }
    return glyph_unknown;
}
