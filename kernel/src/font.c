static const uint8_t glyph_space[FONT_HEIGHT] = {0, 0, 0, 0, 0, 0, 0, 0};

/* Drawn for anything the font does not cover, so a typo in a string shows
 * up on screen rather than vanishing. */
static const uint8_t glyph_unknown[FONT_HEIGHT] = {
    0xF8, 0x88, 0x88, 0x88, 0x88, 0x88, 0xF8, 0x00,
};

const uint8_t *font_glyph(char c)
{
    if (c == ' ') {
        return glyph_space;
    }
    if (c >= 'A' && c <= 'Z') {
        return glyphs_az[c - 'A'];
    }
    return glyph_unknown;
}
